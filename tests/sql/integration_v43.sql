-- Disposable CI database ONLY. These are synthetic accounts, not Supabase production users.
SELECT public.test_assert(NOT has_function_privilege('authenticated','public.dnm_v43_service(text,jsonb)','EXECUTE'),'client cannot call privileged account RPC');
SELECT public.test_assert(NOT has_function_privilege('anon','public.dnm_v43_service(text,jsonb)','EXECUTE'),'anonymous cannot call account RPC');
SELECT public.test_assert(has_function_privilege('service_role','public.dnm_v43_service(text,jsonb)','EXECUTE'),'server role can call account RPC');
SELECT public.test_assert(NOT has_schema_privilege('authenticated','dnm_private','USAGE'),'temporary hashes and tickets remain private');
SELECT public.test_assert(EXISTS(SELECT 1 FROM pg_policies WHERE policyname='dnm_v43_session_gate' AND tablename='dnm_portal_profiles' AND permissive='RESTRICTIVE'),'profile reads gated');
BEGIN;
DO $$
DECLARE a uuid:='11111111-1111-4111-8111-111111111111';
 w uuid:='f0000000-0000-4000-a000-000000000001';
 eid uuid:='f0000000-0000-4000-a000-000000000002';
 sess uuid:='f0000000-0000-4000-a000-000000000003';
 oldsess uuid:='f0000000-0000-4000-a000-000000000004';
 req uuid:=gen_random_uuid();r jsonb;r2 jsonb;cmd jsonb;gen uuid;ev integer;t_hash text:=repeat('a',64);
BEGIN
 PERFORM set_config('request.jwt.claim.sub',a::text,true);
 PERFORM public.test_assert(public.dnm_portal_role()='admin','existing administrator unchanged');
 INSERT INTO public.dnm_v4_records(id,kind,code,title,data,created_by) VALUES(eid,'employee','LOGIN43-TEST','계정 검수 작업자','{"active":false,"department":"생산팀"}',a);
 SELECT version INTO ev FROM public.dnm_v4_records WHERE id=eid;
 cmd:=jsonb_build_object('actor_id',a,'employee_id',eid,'version',ev,'request_id',req,'email','login43@example.invalid','action','provision','reason','CI verified employee');
 r:=public.dnm_v43_service('prepare',cmd);
 PERFORM public.test_assert((r->>'new_user')::boolean,'new Auth account needs creation');
 INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES(w,'login43@example.invalid',jsonb_build_object('display_name','계정 검수 작업자','dnm_employee_id',eid));
 r:=public.dnm_v43_service('finish',jsonb_build_object('actor_id',a,'request_id',req,'profile_id',w,'salt',repeat('b',32),'hash',repeat('c',128)));
 PERFORM public.test_assert(r->>'state'='pending','registration is pending password setup');
 PERFORM public.test_assert((SELECT role='member' AND active FROM public.dnm_portal_profiles WHERE id=w),'new worker gets member role');
 PERFORM public.test_assert((SELECT scope='own' AND can_read AND can_create AND can_update FROM public.dnm_v42_module_access WHERE profile_id=w AND module='worklogs'),'only own work default');
 PERFORM public.test_assert((SELECT data->>'profile_id'=w::text FROM public.dnm_v4_records WHERE id=eid),'worker linked to Auth profile');
 r2:=public.dnm_v43_service('prepare',cmd);PERFORM public.test_assert((r2->>'done')::boolean,'same request cannot create twice');
 INSERT INTO auth.sessions(id,user_id,created_at) VALUES(oldsess,w,clock_timestamp()-interval '1 day');
 PERFORM set_config('request.jwt.claim.sub',w::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',w,'session_id',oldsess)::text,true);
 PERFORM public.test_assert(NOT public.dnm_v43_session_ok(),'pending user cannot access data');
 PERFORM public.test_assert(public.dnm_portal_role() IS NULL,'pending user loses business role');
 PERFORM public.test_assert(NOT public.dnm_v42_allowed('worklogs','create'),'pending user cannot write even with ACL');
 PERFORM public.test_error('SELECT public.dnm_v4_context()','비밀번호');
 PERFORM set_config('request.jwt.claim.sub',a::text,true);
 r:=public.dnm_v43_service('probe',jsonb_build_object('email','login43@example.invalid'));gen:=(r->>'generation')::uuid;
 PERFORM public.test_assert((r->>'valid')::boolean,'pending code is usable only inside server RPC');
 PERFORM public.dnm_v43_service('issue_ticket',jsonb_build_object('profile_id',w,'generation',gen,'hash',t_hash));
 PERFORM public.dnm_v43_service('begin_change',jsonb_build_object('hash',t_hash));
 PERFORM public.dnm_v43_service('finish_change',jsonb_build_object('hash',t_hash));
 PERFORM public.test_assert((SELECT code_hash IS NULL AND code_salt IS NULL AND state='ready' FROM dnm_private.login_controls WHERE profile_id=w),'temporary credential erased after setup');
 PERFORM public.test_error(format('SELECT public.dnm_v43_service(''begin_change'',%L::jsonb)',jsonb_build_object('hash',t_hash)::text),'이미 사용');
 PERFORM set_config('request.jwt.claim.sub',w::text,true);
 PERFORM public.test_assert(NOT public.dnm_v43_session_ok(),'old Auth session stays rejected after first password set');
 INSERT INTO auth.sessions(id,user_id,created_at) VALUES(sess,w,clock_timestamp()+interval '1 second');
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',w,'session_id',sess)::text,true);
 PERFORM public.test_assert(public.dnm_v43_session_ok(),'new personal login permitted');
 PERFORM public.test_assert(public.dnm_v42_allowed('worklogs','create'),'personal session can register own work');
 PERFORM public.test_assert(NOT public.dnm_v42_allowed('orders','read'),'worker does not inherit sales permissions');
 PERFORM public.test_assert(public.dnm_v4_context()->>'account_management'='4.3.0','new account marker without changing v42 business schema');
 PERFORM public.test_error('SELECT public.dnm_v43_accounts()','관리자');
 PERFORM set_config('request.jwt.claim.sub',a::text,true);
 SELECT version INTO ev FROM public.dnm_v4_records WHERE id=eid;
 req:=gen_random_uuid();cmd:=cmd||jsonb_build_object('request_id',req,'action','reset','version',ev);
 r:=public.dnm_v43_service('prepare',cmd);
 PERFORM public.test_assert(NOT (r->>'new_user')::boolean,'reset reuses same Auth ID');
 PERFORM set_config('request.jwt.claim.sub',w::text,true);
 PERFORM public.test_assert(NOT public.dnm_v43_session_ok(),'reset immediately gates previous session');
 PERFORM set_config('request.jwt.claim.sub',a::text,true);
 PERFORM public.dnm_v43_service('finish',jsonb_build_object('actor_id',a,'request_id',req,'profile_id',w,'salt',repeat('d',32),'hash',repeat('e',128)));
 PERFORM public.test_assert((SELECT count(*)=2 FROM public.dnm_v42_module_access WHERE profile_id=w),'reset preserves existing ACL');
 PERFORM public.test_error(format('UPDATE public.dnm_portal_profiles SET role=''admin'' WHERE id=%L',w),'비밀번호 설정');
 SELECT version INTO ev FROM public.dnm_v4_records WHERE id=eid;
 req:=gen_random_uuid();cmd:=cmd||jsonb_build_object('request_id',req,'action','disable','version',ev);
 PERFORM public.dnm_v43_service('prepare',cmd);
 PERFORM public.test_assert((SELECT count(*)=1 FROM auth.users WHERE id=w),'disable never deletes account');
 PERFORM public.test_assert((SELECT NOT active FROM public.dnm_portal_profiles WHERE id=w),'disable inactive profile');
 PERFORM public.test_assert((SELECT state='disabled' AND NOT enabled FROM dnm_private.login_controls WHERE profile_id=w),'disable gates credentials');
 PERFORM public.test_assert((SELECT count(*)=2 FROM public.dnm_v42_module_access WHERE profile_id=w),'disable retains permissions for approved later reuse');
 PERFORM public.test_assert((public.dnm_v43_service('rate','{"bucket":"test43","limit":1,"seconds":60}')->>'allowed')::boolean,'first rate request allowed');
 PERFORM public.test_assert(NOT (public.dnm_v43_service('rate','{"bucket":"test43","limit":1,"seconds":60}')->>'allowed')::boolean,'rate counter is durable');
 PERFORM public.test_assert((SELECT count(*)>=3 FROM public.dnm_portal_audit WHERE entity='login_account' AND record_id=w::text),'account lifecycle audit retained');
END $$;
